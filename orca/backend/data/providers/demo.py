    @staticmethod
    def _is_ocean(lat: float, lon: float) -> bool:
        """Check if a coordinate is likely in the ocean (not on land).

        Uses refined land regions so that ocean areas (Bay of Bengal,
        Arabian Sea, Indian Ocean) are correctly classified as water.
        """
        # Outside any reasonable Indian Ocean area
        if lat < 0 or lat > 36 or lon < 60 or lon > 98:
            return False

        # ── Land first (so peninsulas inside the "outer water" bands below are
        # correctly treated as land) ────────────────────────────────

        # Sri Lanka (whole island ~5.9-10N; south of it is open Indian Ocean). The
        # lon floor (~79.9E) keeps Palk Bay / Gulf of Mannar water west of Jaffna.
        if 5.9 <= lat <= 10.0 and 79.9 <= lon <= 82.0:
            return False

        # Everything north of ~23N within the region is land (Pakistan, Rajasthan,
        # UP/Bihar, Bangladesh, NE India, Tibet) for lon >= 68E. West of that
        # (lon < 68E) is the open Arabian Sea off the Pakistan/Makran coast.
        if lat >= 23 and lon >= 68:
            return False

        # Saurashtra peninsula (Gujarat) — sea lies west (~lon<69.3) and around the
        # peninsula, and the Gulf of Khambhat at 21-22.4N/71.9-72.8E stays water.
        if 21.3 <= lat < 22.5 and 69.3 <= lon <= 71.9:
            return False

        # Mainland Gujarat north of the Gulf of Khambhat head (~22.5N)
        if 22.5 <= lat < 23 and 71.7 <= lon <= 74.0:
            return False

        # Mumbai / Konkan coast landmass. The lower lon bound (72.7) keeps the
        # Arabian Sea strip west of Mumbai (~72.0-72.6E) classified as water.
        if 18 <= lat <= 20 and 72.7 <= lon < 73.5:
            return False

        # Central India interior: MP, Chhattisgarh, Jharkhand, Andhra interior.
        # West edge 73.5E also covers the Pune/Konkan hinterland gap at lat 18-20.
        if 18 <= lat < 23 and 73.5 <= lon <= 80:
            return False

        # Odisha interior (coast at ~86-87E)
        if 19 <= lat < 23 and 80 < lon <= 85:
            return False

        # Western + Central South India: Maharashtra, Goa, Karnataka, Telangana, Andhra interior
        if 14 <= lat < 18 and 74 <= lon <= 80:
            return False

        # Andhra interior east of the Krishna delta (coast here runs ~81.2-82.3E);
        # catches inland cities such as Vijayawada (16.5N, 80.65E).
        if 16.0 <= lat < 17.5 and 80.0 <= lon <= 81.4:
            return False

        # South India interior: Kerala/Tamil Nadu interior
        # Tamil Nadu coast is at ~80.0-80.3E, extend block to 80.0
        if 10 <= lat < 14 and 75.5 <= lon <= 80.0:
            return False

        # Far-south Tamil Nadu / Kerala interior (below the 10N block, above the
        # tip). Kept inside lon 76.8-79.0 so the Kerala sea (west) and the Gulf of
        # Mannar / Palk Bay (east, ~79.2-80.3E) remain water.
        if 8.5 <= lat < 10 and 76.8 <= lon <= 79.0:
            return False

        # ── Outer ocean: always water ──────────────────────────
        # Far Arabian Sea (off Gujarat/Sindh; Saurashtra itself is handled above)
        if lon < 72 and lat < 22:
            return True
        # Far Bay of Bengal (east of Indian landmass, south of WB/Bangladesh)
        if lon > 86 and lat < 23:
            return True
        # Southern Indian Ocean (south of the subcontinent & Sri Lanka)
        if lat < 7:
            return True

        # ── Everything else near India is ocean ────────────────
        return True

    async def get_data(
        self,
        bbox: list[float],
        start_date: datetime,
        end_date: datetime,
        variables: list[str],
        **kwargs,
    ) -> ObservationBatch:
        """Generate demo observations for the requested region and time."""
        observations = []

        # Strip timezone info for consistency
        if start_date.tzinfo is not None:
            start_date = start_date.replace(tzinfo=None)
        if end_date.tzinfo is not None:
            end_date = end_date.replace(tzinfo=None)

        # Spatial grid: ~0.25 degree resolution
        lat_step = 0.25
        lon_step = 0.25
        west, south, east, north = bbox

        # Temporal: daily resolution
        current_date = start_date
        day_count = 0

        while current_date <= end_date:
            day_of_year = current_date.timetuple().tm_yday

            lat = south
            while lat <= north:
                lon = west
                while lon <= east:
                    # Skip land points
                    if not self._is_ocean(lat, lon):
                        lon += lon_step
                        continue
                    for var_name in variables:
                        if var_name not in self.VARIABLE_DEFS:
                            continue

                        var_def = self.VARIABLE_DEFS[var_name]
                        value = self._compute_variable(
                            var_name, lat, lon, current_date, day_of_year, bbox
                        )

                        # Add controlled anomaly near Goa (15-16°N, 72-73°E) in August
                        value = self._apply_anomaly(
                            var_name, value, lat, lon, current_date, day_of_year
                        )

                        obs = self._create_observation(
                            dataset="demo_synthetic",
                            variable=var_name,
                            value=round(value, 4),
                            unit=var_def["unit"],
                            latitude=round(lat, 4),
                            longitude=round(lon, 4),
                            timestamp=current_date,
                            quality=round(0.85 + self._rng.random() * 0.15, 3),
                            metadata={
                                "grid_resolution_deg": 0.25,
                                "temporal_resolution": "daily",
                                "data_mode": "DEMO",
                                "label": "SYNTHETIC DATA — NOT LIVE OBSERVATIONS",
                            },
                            is_demo=True,
                        )
                        observations.append(obs)

                    lon += lon_step
                lat += lat_step

            current_date += timedelta(days=1)
            day_count += 1

        self._last_successful_retrieval = datetime.utcnow()

        return ObservationBatch(
            observations=observations,
            source="DEMO",
            dataset="demo_synthetic",
            bbox=bbox,
            date_range=(start_date, end_date),
            record_count=len(observations),
            is_demo=True,
        )

    def _compute_variable(
        self,
        var_name: str,
        lat: float,
        lon: float,
        date: datetime,
        day_of_year: int,
        bbox: list[float],
    ) -> float:
        """Compute a realistic value for a variable at a given location/time."""

        var_def = self.VARIABLE_DEFS[var_name]
        low, high = var_def["base_range"]

        # Latitude factor (south is warmer for SST)
        lat_factor = (lat - 8.0) / 16.0  # 0 at south, 1 at north

        # Longitude factor (closer to coast = more coastal effects)
        lon_factor = (lon - 68.0) / 10.0

        # Seasonal factor (monsoon = June-September)
        month = date.month
        seasonal = 0.5 + 0.5 * math.sin(2 * math.pi * (month - 3) / 12.0)

        # Deterministic seed from coordinates + date
        seed_val = hashlib.md5(
            f"{lat:.2f},{lon:.2f},{date.isoformat()}".encode()
        ).hexdigest()
        seed_int = int(seed_val[:8], 16)
        rng = np.random.default_rng(seed_int)
        noise = rng.normal(0, (high - low) * 0.1)

        if var_name == "sea_surface_temperature":
            # SST: warmer south, seasonal cycle
            base = 30.0 - lat_factor * 5.0 + seasonal * 1.5
            return max(low, min(high, base + noise))

        elif var_name == "chlorophyll_concentration":
            # Chlorophyll: higher near coast, seasonal upwelling
            coastal_boost = max(0, 1.0 - lon_factor) * 3.0
            monsoon_boost = seasonal * 2.0 if month in (6, 7, 8, 9) else 0
            base = 0.5 + coastal_boost + monsoon_boost
            # Log-normal distribution
            return max(low, min(high, base * math.exp(rng.normal(0, 0.3))))

        elif var_name == "salinity":
            # Salinity: higher offshore, lower near rivers
            base = 34.0 + lon_factor * 2.0 - seasonal * 0.5
            return max(low, min(high, base + noise * 0.3))

        elif var_name == "wind_speed":
            # Monsoon winds
            monsoon_factor = 1.5 if month in (6, 7, 8, 9) else 0.7
            base = 6.0 * monsoon_factor + lat_factor * 2.0
            return max(low, min(high, base + abs(noise)))

        elif var_name == "wind_direction":
            # SW monsoon in summer, NE in winter
            if month in (6, 7, 8, 9):
                base = 225 + rng.normal(0, 30)  # SW
            elif month in (12, 1, 2):
                base = 45 + rng.normal(0, 30)  # NE
            else:
                base = 180 + rng.normal(0, 45)
            return base % 360

        elif var_name == "wave_height":
            # Significant wave height: monsoon swells (Jun-Sep), southern ocean
            monsoon_boost = 3.0 if month in (6, 7, 8, 9) else 0.4
            lat_boost = max(0, (lat - 6.0) * 0.15)
            base = 0.6 + monsoon_boost * seasonal + lat_boost
            return max(low, min(high, base + abs(noise) * 1.2))

        elif var_name == "wave_period":
            # Swell period follows wave height
            base = 6.0 + seasonal * 8.0
            return max(low, min(high, base + noise * 2.0))

        elif var_name == "sea_surface_current_u":
            # Eastward currents
            base = 0.1 * math.sin(2 * math.pi * day_of_year / 365)
            return max(low, min(high, base + noise * 0.5))

        elif var_name == "sea_surface_current_v":
            # Northward currents
            base = 0.05 * math.cos(2 * math.pi * day_of_year / 365)
            return max(low, min(high, base + noise * 0.3))

        elif var_name == "fishing_activity":
            # Higher near coast, seasonal
            coastal_factor = max(0, 1.2 - lon_factor)
            base = 0.8 * coastal_factor * (1.0 + seasonal * 0.3)
            return max(low, min(high, base + abs(noise * 0.3)))

        elif var_name == "sea_level":
            base = 0.1 * math.sin(2 * math.pi * day_of_year / 365)
            return max(low, min(high, base + noise * 0.2))

        elif var_name == "ocean_color_index":
            coastal_factor = max(0, 1.0 - lon_factor) * 3.0
            base = 0.3 + coastal_factor * 0.2
            return max(low, min(high, base + noise * 0.2))

        else:
            return (low + high) / 2 + noise

    def _apply_anomaly(
        self,
        var_name: str,
        value: float,
        lat: float,
        lon: float,
        date: datetime,
        day_of_year: int,
    ) -> float:
        """Apply controlled anomaly near Goa (15-16°N, 72-73°E) in August 2026.

        This creates a clear signal for the reasoning pipeline to detect:
        - SST spike (+2°C)
        - Chlorophyll drop (-30%)
        - Reduced wind mixing
        - Slightly elevated fishing
        """

        # Anomaly region: 14.5-16.5°N, 71.5-73.5°E
        in_anomaly_region = 14.5 <= lat <= 16.5 and 71.5 <= lon <= 73.5
        # Anomaly time: July 15 - August 28, 2026
        anomaly_start = datetime(2026, 7, 15)
        anomaly_end = datetime(2026, 8, 28)
        in_anomaly_time = anomaly_start <= date <= anomaly_end

        if not (in_anomaly_region and in_anomaly_time):
            return value

        # Gaussian spatial decay from center (15.5, 72.5)
        dist = math.sqrt((lat - 15.5) ** 2 + (lon - 72.5) ** 2)
        spatial_decay = math.exp(-(dist ** 2) / 1.0)

        # Temporal ramp: peaks around Aug 1-15
        days_into = (date - anomaly_start).days
        total_days = (anomaly_end - anomaly_start).days
        temporal_envelope = math.exp(
            -((days_into - total_days * 0.4) ** 2) / (2 * (total_days * 0.3) ** 2)
        )

        strength = spatial_decay * temporal_envelope

        if var_name == "sea_surface_temperature":
            return value + 2.0 * strength  # +2°C spike
        elif var_name == "chlorophyll_concentration":
            return value * (1.0 - 0.35 * strength)  # 35% reduction
        elif var_name == "wind_speed":
            return value * (1.0 - 0.25 * strength)  # 25% wind reduction
        elif var_name == "sea_surface_current_u":
            return value * (1.0 - 0.3 * strength)  # Reduced current
        elif var_name == "fishing_activity":
            return value * (1.0 + 0.2 * strength)  # Slight fishing increase
        elif var_name == "salinity":
            return value + 0.5 * strength  # Slight salinity increase
        else:
            return value
